"""
GrowthIQ Cohort Retention Analytics Module
------------------------------------------
Constructs monthly customer acquisition cohorts and calculates retention rate
matrices, cohort revenue accumulation, and lifetime value trajectories.
"""

from typing import Tuple, Dict, Any
import pandas as pd
import numpy as np
from src.analytics.kpis import order_facts


def build_cohort_matrices(
    orders: pd.DataFrame, items: pd.DataFrame = None
) -> Tuple[pd.DataFrame, pd.DataFrame, pd.DataFrame]:
    """
    Builds the monthly cohort retention rate matrix, active customer count matrix,
    and cumulative revenue matrix.

    Returns:
    - retention_matrix: Percentage of initial cohort returning in month t (0.0 to 1.0)
    - counts_matrix: Number of distinct customers purchasing in month t
    - revenue_matrix: Total revenue generated by each cohort in month t
    """
    if orders.empty:
        empty = pd.DataFrame()
        return empty, empty, empty

    df = orders[orders["order_status"] == "Completed"].copy() if "order_status" in orders.columns else orders.copy()
    if df.empty:
        empty = pd.DataFrame()
        return empty, empty, empty

    if not pd.api.types.is_datetime64_any_dtype(df["order_date"]):
        df["order_date"] = pd.to_datetime(df["order_date"])

    # If items supplied, calculate line revenue, else fallback to 1.0
    if items is not None and not items.empty:
        facts = order_facts(df, items)
    else:
        facts = df.copy()
        if "revenue_inr" not in facts.columns:
            facts["revenue_inr"] = 0.0

    facts["order_month"] = facts["order_date"].dt.to_period("M")

    # Cohort month = customer's earliest order month
    cohort_min = facts.groupby("customer_id")["order_month"].min().rename("cohort_month")
    facts = facts.join(cohort_min, on="customer_id")

    # Calculate integer period index (0 for initial purchase month, 1 for next month, etc.)
    facts["period_number"] = (
        (facts["order_month"].dt.year - facts["cohort_month"].dt.year) * 12
        + (facts["order_month"].dt.month - facts["cohort_month"].dt.month)
    )

    # 1. Group by cohort_month and period_number
    grouped = (
        facts.groupby(["cohort_month", "period_number"])
        .agg(
            active_customers=("customer_id", "nunique"),
            revenue_inr=("revenue_inr", "sum"),
            orders=("order_id", "nunique"),
        )
        .reset_index()
    )

    # Base cohort size (active customers at period 0)
    base_sizes = grouped[grouped["period_number"] == 0][["cohort_month", "active_customers"]].rename(
        columns={"active_customers": "cohort_size"}
    )
    grouped = grouped.merge(base_sizes, on="cohort_month")
    grouped["retention_rate"] = grouped["active_customers"] / grouped["cohort_size"]

    # Pivot to matrices
    counts_matrix = grouped.pivot(index="cohort_month", columns="period_number", values="active_customers").fillna(0).astype(int)
    retention_matrix = grouped.pivot(index="cohort_month", columns="period_number", values="retention_rate").fillna(0.0)
    revenue_matrix = grouped.pivot(index="cohort_month", columns="period_number", values="revenue_inr").fillna(0.0)

    # Convert period index to string labels
    counts_matrix.columns = [f"M{col}" for col in counts_matrix.columns]
    retention_matrix.columns = [f"M{col}" for col in retention_matrix.columns]
    revenue_matrix.columns = [f"M{col}" for col in revenue_matrix.columns]

    # Convert cohort index to formatted string (e.g. '2025-01')
    counts_matrix.index = counts_matrix.index.astype(str)
    retention_matrix.index = retention_matrix.index.astype(str)
    revenue_matrix.index = revenue_matrix.index.astype(str)

    return retention_matrix, counts_matrix, revenue_matrix


def cohort_summary_metrics(retention_matrix: pd.DataFrame, counts_matrix: pd.DataFrame) -> Dict[str, Any]:
    """Computes high-level cohort retention benchmarks."""
    if retention_matrix.empty or counts_matrix.empty:
        return {"avg_m1_retention": 0.0, "total_cohorts": 0, "total_cohort_customers": 0}

    total_cohorts = len(retention_matrix)
    total_customers = int(counts_matrix["M0"].sum()) if "M0" in counts_matrix.columns else 0

    m1_rates = retention_matrix["M1"].dropna() if "M1" in retention_matrix.columns else pd.Series()
    # Exclude cohorts that haven't reached M1 yet (e.g. December)
    valid_m1 = m1_rates[m1_rates > 0]
    avg_m1 = float(valid_m1.mean()) if not valid_m1.empty else 0.0

    m3_rates = retention_matrix["M3"].dropna() if "M3" in retention_matrix.columns else pd.Series()
    valid_m3 = m3_rates[m3_rates > 0]
    avg_m3 = float(valid_m3.mean()) if not valid_m3.empty else 0.0

    return {
        "total_cohorts": total_cohorts,
        "total_cohort_customers": total_customers,
        "avg_m1_retention": avg_m1,
        "avg_m3_retention": avg_m3,
    }

