"""
GrowthIQ — Page 6: Cohort Retention & Customer Lifecycle
========================================================
Monthly customer acquisition cohorts: retention rate triangles, repeat purchase
cadence, and cumulative revenue accumulation over customer tenure.
"""

import streamlit as st
import pandas as pd
import numpy as np
from src.visualisation.ui import (
    inject_custom_css,
    render_sidebar,
    render_metric_card,
    render_insights_box,
    render_table_with_export,
    COLOR_BURGUNDY,
    COLOR_GOLD,
    COLOR_TAUPE,
)
from src.analytics.cohorts import build_cohort_matrices, cohort_summary_metrics
from src.visualisation.charts import plot_cohort_heatmap

st.set_page_config(
    page_title="Cohort Analysis | GrowthIQ",
    page_icon="📅",
    layout="wide",
    initial_sidebar_state="expanded",
)

inject_custom_css()
ctx = render_sidebar()

orders = ctx["orders"]
items = ctx["order_items"]

st.markdown(
    """
    <div style="margin-bottom: 1.2rem;">
        <h1 style="margin-bottom: 0.1rem;">Customer Cohort Retention Analysis</h1>
        <div style="font-size: 0.88rem; color: #6B5C60;">
            Longitudinal customer lifecycle tracking: cohort retention matrices, repeat repurchase velocity, and lifetime value build-up.
        </div>
    </div>
    """,
    unsafe_allow_html=True,
)

# Compute Cohort Matrices
ret_matrix, counts_matrix, rev_matrix = build_cohort_matrices(orders, items)

if ret_matrix.empty:
    st.warning("Insufficient order data to compute cohort retention.")
    st.stop()

# Headline Cohort Benchmarks
summary = cohort_summary_metrics(ret_matrix, counts_matrix)

c1, c2, c3, c4 = st.columns(4)
with c1:
    st.markdown(render_metric_card("Tracked Cohorts", f"{summary['total_cohorts']}", "Monthly acquisition batches"), unsafe_allow_html=True)
with c2:
    st.markdown(render_metric_card("Acquired Buyers", f"{summary['total_cohort_customers']:,}", "Initial Month 0 (M0) customer base"), unsafe_allow_html=True)
with c3:
    st.markdown(render_metric_card("Average M1 Retention", f"{summary['avg_m1_retention']:.1%}", "Repurchasing in Month 1"), unsafe_allow_html=True)
with c4:
    st.markdown(render_metric_card("Average M3 Retention", f"{summary['avg_m3_retention']:.1%}", "Repurchasing in Month 3"), unsafe_allow_html=True)

# Cohort Lifecycle Insights
insights = []
if summary["avg_m1_retention"] > 0:
    insights.append(
        f"**First-Month Repurchase Velocity:** On average, **{summary['avg_m1_retention']:.1%}** of newly acquired customers place a repeat order within 30 days of their initial purchase."
    )
if not ret_matrix.empty and "M1" in ret_matrix.columns:
    m1_series = ret_matrix["M1"].dropna()
    valid_m1 = m1_series[m1_series > 0]
    if not valid_m1.empty:
        best_cohort = valid_m1.idxmax()
        best_m1_val = valid_m1.max()
        insights.append(
            f"**Strongest Cohort Quality:** The **{best_cohort}** cohort recorded the highest Month 1 retention at **{best_m1_val:.1%}**, indicating exceptional post-purchase product satisfaction and fit."
        )
insights.append(
    "**Customer Lifecycle Strategy:** Repeat purchases stabilize around months 3-6. Implementing a post-purchase 45-day replenishment email cadence (for essentials like sports bras & leggings) creates a predictable recurring revenue stream."
)

render_insights_box("Cohort Retention Insights & Lifecycle Strategy", insights)

st.markdown("---")

# Visual Heatmap
st.plotly_chart(plot_cohort_heatmap(ret_matrix), use_container_width=True)

st.markdown("---")

# Tabbed Cohort Data Tables: Percentages vs Counts vs Revenue
tab_pct, tab_cnt, tab_rev = st.tabs(
    ["Retention Rate Matrix (%)", "Active Buyer Counts", "Cohort Revenue Trajectory (INR)"]
)

with tab_pct:
    st.subheader("Monthly Retention Rate Triangle (%)")
    st.caption("Percentage of original cohort size making a completed purchase in subsequent months.")
    render_table_with_export(
        ret_matrix.reset_index().rename(columns={"index": "Cohort"}),
        filename="growthiq_cohort_retention_rates",
        label="Export Retention Rates (CSV)",
        format_dict={col: "{:.1%}" for col in ret_matrix.columns},
    )

with tab_cnt:
    st.subheader("Active Repeat Customer Counts")
    st.caption("Distinct purchasing customers in each period month.")
    render_table_with_export(
        counts_matrix.reset_index().rename(columns={"index": "Cohort"}),
        filename="growthiq_cohort_active_counts",
        label="Export Buyer Counts (CSV)",
        format_dict={col: "{:,}" for col in counts_matrix.columns},
    )

with tab_rev:
    st.subheader("Cumulative Cohort Revenue (INR)")
    st.caption("Gross revenue generated by each monthly acquisition cohort over time.")
    render_table_with_export(
        rev_matrix.reset_index().rename(columns={"index": "Cohort"}),
        filename="growthiq_cohort_revenue_trajectory",
        label="Export Cohort Revenue (CSV)",
        format_dict={col: "₹{:,.0f}" for col in rev_matrix.columns},
    )

